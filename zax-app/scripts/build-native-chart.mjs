import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
const result = await build({
  entryPoints: ["lib/trading/native-chart-entry.ts"],
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "es2020",
  minify: true,
  write: false,
  legalComments: "inline",
});
const script = result.outputFiles[0].text;
await mkdir("lib/trading/generated", { recursive: true });
await writeFile(
  "lib/trading/generated/lightweight-runtime.ts",
  `// Generated by scripts/build-native-chart.mjs. Local display-only runtime; includes Apache-2.0 vendor notices.\nexport const NATIVE_CHART_SCRIPT = ${JSON.stringify(script)};\n`,
);
console.log(
  `Native chart runtime bundled locally: ${Buffer.byteLength(script)} bytes.`,
);
